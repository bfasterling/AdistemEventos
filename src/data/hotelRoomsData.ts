/**
 * Utility to parse raw text lines into structured HotelRoom objects.
 * Supports CSV, TSV (Excel copy-paste), or dash-separated formats:
 * Examples:
 * 101, King Deluxe
 * 102	Doble Queen
 * 103 - Ocean View King
 * Habitación 104: Master Suite
 */
export function parseHotelRoomsText(text: string, hotelName: string = "Rosewood Mandarina"): HotelRoom[] {
  if (!text || !text.trim()) return [];

  const lines = text.split(/\r?\n/).map(l => l.trim()).filter(Boolean);
  const rooms: HotelRoom[] = [];
  const seenNumbers = new Set<string>();

  for (const line of lines) {
    // Skip table header lines like "Numero,Tipo" or "Habitacion	Tipo"
    if (/^(numero|número|habitacion|habitación|room|no\.)/i.test(line)) {
      continue;
    }

    let numero = "";
    let tipo = "";

    if (line.includes("\t")) {
      const parts = line.split("\t").map(p => p.trim());
      numero = parts[0] || "";
      tipo = parts[1] || "Estándar";
    } else if (line.includes(",")) {
      const parts = line.split(",").map(p => p.trim());
      numero = parts[0] || "";
      tipo = parts.slice(1).join(", ").trim() || "Estándar";
    } else if (line.includes("-")) {
      const parts = line.split("-").map(p => p.trim());
      numero = parts[0] || "";
      tipo = parts.slice(1).join(" - ").trim() || "Estándar";
    } else if (line.includes(":")) {
      const parts = line.split(":").map(p => p.trim());
      numero = parts[0] || "";
      tipo = parts.slice(1).join(": ").trim() || "Estándar";
    } else {
      // Just a single word or room number
      const parts = line.split(/\s+/);
      numero = parts[0] || "";
      tipo = parts.slice(1).join(" ").trim() || "Estándar";
    }

    // Clean up room number
    numero = numero.replace(/^(hab\.|habitación|room)\s*/i, "").trim();
    if (!numero) continue;

    if (!seenNumbers.has(numero.toLowerCase())) {
      seenNumbers.add(numero.toLowerCase());
      rooms.push({
        numero,
        tipo: tipo || "Habitación Estándar",
        hotel: hotelName,
      });
    }
  }

  return rooms;
}
